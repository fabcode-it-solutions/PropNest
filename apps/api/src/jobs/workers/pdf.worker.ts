import { Worker } from 'bullmq'
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib'
import { redis } from '../../config/redis.js'
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const connection = redis as any
import { query } from '../../config/db.js'
import { s3 } from '../../config/s3.js'
import { PutObjectCommand } from '@aws-sdk/client-s3'
import { env } from '../../config/env.js'

export const pdfWorker = new Worker(
  'pdf-generation',
  async (job) => {
    if (job.name !== 'generate-preapproval-letter') return

    const { applicationId } = job.data as { applicationId: string }

    const res = await query<{
      id: string
      buyer_id: string
      pre_approval_amount: number
      loan_type: string
      property_value: number
      credit_score: number
      buyer_first_name: string
      buyer_last_name: string
      lender_first_name: string
      lender_last_name: string
      agency_name: string | null
    }>(
      `SELECT ma.id, ma.buyer_id, ma.pre_approval_amount, ma.loan_type,
              ma.property_value, ma.credit_score,
              b.first_name AS buyer_first_name, b.last_name AS buyer_last_name,
              l.first_name AS lender_first_name, l.last_name AS lender_last_name,
              ag.agency_name
       FROM mortgage_applications ma
       JOIN users b ON b.id = ma.buyer_id
       LEFT JOIN users l ON l.id = ma.lender_id
       LEFT JOIN agents ag ON ag.user_id = ma.lender_id
       WHERE ma.id = $1`,
      [applicationId]
    )

    const app = res.rows[0]
    if (!app) throw new Error(`Application ${applicationId} not found`)

    // ── Build PDF ──────────────────────────────────────────────────────────
    const pdfDoc = await PDFDocument.create()
    const page = pdfDoc.addPage([612, 792]) // Letter size

    const timesRoman = await pdfDoc.embedFont(StandardFonts.TimesRoman)
    const timesBold = await pdfDoc.embedFont(StandardFonts.TimesRomanBold)

    const navy = rgb(0.106, 0.176, 0.310) // #1B2D4F
    const black = rgb(0, 0, 0)
    const gray = rgb(0.4, 0.4, 0.4)

    // Header
    page.drawText('PROPNEST', {
      x: 50,
      y: 740,
      size: 28,
      font: timesBold,
      color: navy,
    })

    page.drawText('Pre-Approval Letter', {
      x: 50,
      y: 710,
      size: 16,
      font: timesRoman,
      color: navy,
    })

    // Divider line
    page.drawLine({
      start: { x: 50, y: 700 },
      end: { x: 562, y: 700 },
      thickness: 1,
      color: navy,
    })

    const today = new Date().toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    })

    page.drawText(`Date: ${today}`, { x: 50, y: 680, size: 11, font: timesRoman, color: gray })

    // Salutation
    page.drawText(
      `To Whom It May Concern,`,
      { x: 50, y: 650, size: 12, font: timesRoman, color: black }
    )

    // Body
    const amount = app.pre_approval_amount?.toLocaleString('en-US', {
      style: 'currency',
      currency: 'USD',
      maximumFractionDigits: 0,
    }) ?? '$0'

    const lenderName = app.lender_first_name
      ? `${app.lender_first_name} ${app.lender_last_name}`
      : 'PropNest Lending'

    const buyerName = `${app.buyer_first_name} ${app.buyer_last_name}`

    const bodyLines = [
      `This letter confirms that ${buyerName} has been pre-approved`,
      `for a ${app.loan_type?.replace(/_/g, ' ')} mortgage in the amount of ${amount}.`,
      '',
      `This pre-approval is based on:`,
      `  • Credit Score: ${app.credit_score ?? 'N/A'}`,
      `  • Property Value: ${app.property_value?.toLocaleString('en-US', { style: 'currency', currency: 'USD', maximumFractionDigits: 0 }) ?? 'N/A'}`,
      '',
      `This pre-approval is valid for 90 days from the date above and is contingent upon`,
      `verification of the information provided, satisfactory appraisal of the property,`,
      `and no material changes to the applicant's financial situation.`,
      '',
      `Please do not hesitate to contact us if you have any questions.`,
    ]

    let y = 620
    for (const line of bodyLines) {
      page.drawText(line, { x: 50, y, size: 12, font: timesRoman, color: black })
      y -= 20
    }

    // Signature
    y -= 20
    page.drawText('Sincerely,', { x: 50, y, size: 12, font: timesRoman, color: black })
    y -= 40
    page.drawText(lenderName, { x: 50, y, size: 12, font: timesBold, color: black })
    if (app.agency_name) {
      y -= 20
      page.drawText(app.agency_name, { x: 50, y, size: 11, font: timesRoman, color: gray })
    }
    y -= 20
    page.drawText('PropNest Platform', { x: 50, y, size: 11, font: timesRoman, color: gray })

    // Footer
    page.drawText(
      `This document was generated by PropNest | ${env.APP_URL}`,
      { x: 50, y: 40, size: 9, font: timesRoman, color: gray }
    )

    const pdfBytes = await pdfDoc.save()

    // Upload to S3
    const s3Key = `mortgage/${applicationId}/preapproval-letter.pdf`
    await s3.send(
      new PutObjectCommand({
        Bucket: env.S3_BUCKET,
        Key: s3Key,
        Body: Buffer.from(pdfBytes),
        ContentType: 'application/pdf',
        ContentDisposition: `attachment; filename="pre-approval-${applicationId}.pdf"`,
      })
    )

    await query(
      `UPDATE mortgage_applications SET pre_approval_letter_s3_key = $1 WHERE id = $2`,
      [s3Key, applicationId]
    )
  },
  {
    connection,
    concurrency: 2,
  }
)

pdfWorker.on('failed', (job, err) => {
  console.error(`[pdf-worker] Job ${job?.id} failed:`, err.message)
})
